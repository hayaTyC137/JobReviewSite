package com.jobreview.user;

/**
 * Роли пользователей платформы (RBAC).
 * USER — сотрудник/соискатель: пишет отзывы, ведёт карточку сотрудника.
 * REPRESENTATIVE — официальный представитель компании (директор, HR): управляет профилем
 * организации, ведёт трудовую историю и оценки своих сотрудников, обжалует отзывы.
 * MODERATOR — очереди модерации: компании, изменения профилей, жалобы, обжалования, обращения.
 * ADMIN — всё, что может модератор, плюс управление пользователями, ролями, контентом и настройками.
 */
public enum Role {
    USER,
    REPRESENTATIVE,
    MODERATOR,
    ADMIN;

    /** Сотрудник платформы: модератор или администратор */
    public boolean isStaff() {
        return this == MODERATOR || this == ADMIN;
    }
}
