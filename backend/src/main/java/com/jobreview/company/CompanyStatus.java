package com.jobreview.company;

/**
 * Статус компании в реестре.
 * PENDING — заявка на добавление ждёт проверки модератором, компания не видна в поиске.
 * APPROVED — проверена и опубликована.
 * REJECTED — заявка отклонена; представитель может исправить данные и отправить её снова.
 * SUSPENDED — публикация приостановлена администратором (например, по результатам жалоб).
 */
public enum CompanyStatus {
    PENDING,
    APPROVED,
    REJECTED,
    SUSPENDED
}
