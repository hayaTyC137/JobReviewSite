package com.jobreview.model;

/**
 * Роли пользователей платформы.
 * USER — обычный соискатель/сотрудник, пишет отзывы.
 * REPRESENTATIVE — официальный представитель компании (директор, HR-директор),
 * может обжаловать отзывы о своей компании.
 * MODERATOR — разбирает заявки на обжалование и подтверждает представителей.
 */
public enum Role {
    USER,
    REPRESENTATIVE,
    MODERATOR
}
